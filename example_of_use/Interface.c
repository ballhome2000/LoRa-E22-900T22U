/*
********************************************************************************
*	InterfaceOpen
********************************************************************************
*/
int32_t InterfaceOpen(void) {

	//--------------------------------------------------------------------------
	fd = open( "/dev/serial/by-id/usb-1a86_USB_Serial-if00-port0", O_RDWR | O_NOCTTY );
	//--------------------------------------------------------------------------
    if( fd == -1 ) {
		//----------------------------------------------------------------------
        perror( "Error opening UART" );
		//----------------------------------------------------------------------
        return -1;
    }
    //--------------------------------------------------------------------------
 struct termios tty;
	//--------------------------------------------------------------------------
    if( tcgetattr( fd, &tty ) != 0 ) {
		//----------------------------------------------------------------------
        perror( "Error from tcgetattr" );
        close(fd);
		//----------------------------------------------------------------------
        return -1;
    }
    //--------------------------------------------------------------------------
    cfsetospeed( &tty, B115200 );
    cfsetispeed( &tty, B115200 );
	//--------------------------------------------------------------------------
    tty.c_cflag &= ~PARENB;        // No parity bit
    tty.c_cflag &= ~CSTOPB;        // 1 stop bit
    tty.c_cflag &= ~CSIZE;
    tty.c_cflag |= CS8;            // 8 data bits
    tty.c_cflag &= ~CRTSCTS;       // Disable RTS/CTS hardware flow control
    tty.c_cflag |= CREAD | CLOCAL; // Turn on READ & ignore ctrl lines
    //--------------------------------------------------------------------------
    tty.c_lflag &= ~(ICANON | ECHO | ECHOE | ISIG);
    tty.c_iflag &= ~(IXON | IXOFF | IXANY);
    tty.c_iflag &= ~(IGNBRK | BRKINT | PARMRK | ISTRIP | INLCR | IGNCR | ICRNL);
    tty.c_oflag &= ~OPOST;
	//--------------------------------------------------------------------------
    tty.c_cc[VMIN] = 0;
    tty.c_cc[VTIME] = 5; // 5 * 0.1s = 0.5s
	//--------------------------------------------------------------------------
    if( tcsetattr(fd, TCSANOW, &tty ) != 0 ) {
		//----------------------------------------------------------------------
        perror( "Error from tcsetattr" );
        close(fd);
		//----------------------------------------------------------------------
        return -1;
    }
    //--------------------------------------------------------------------------
    return 0;
}

/*
********************************************************************************
*	InterfaceClose
********************************************************************************
*/
void InterfaceClose(void) {

	//--------------------------------------------------------------------------
	close(fd);
	//--------------------------------------------------------------------------
}

/*
********************************************************************************
*	GetStatus
********************************************************************************
*/
int16_t GetStatus(	uint8_t		Opcode,
					uint8_t*	pStatus,
					uint8_t*	pData,
					uint8_t		Len ) {

 uint8_t	Index;
 uint8_t	Byte;

	//--------------------------------------------------------------------------
	write( fd, "\x55", 1 ); // Start
	//--------------------------------------------------------------------------
	write( fd, &Opcode, 1 ); read( fd, &Byte, 1 ); // Opcode
	//--------------------------------------------------------------------------
	Byte = Len + 1;
	write( fd, &Byte, 1 ); // Len
	//--------------------------------------------------------------------------
	write( fd, "\x00", 1 ); read( fd, &Byte, 1 ); // NOP/Status
	if( pStatus != NULL )
		*pStatus = Byte & 0x7E;
	//--------------------------------------------------------------------------
	for( Index = 0; Index < Len; Index++ ) {
		//----------------------------------------------------------------------
		write( fd, "\xFF", 1 ); read( fd, &Byte, 1 ); // Read Data
		//----------------------------------------------------------------------
		if( pData != NULL )
			pData[Index] = Byte;
		//----------------------------------------------------------------------
	}
	//--------------------------------------------------------------------------
	write( fd, "\xAA", 1 ); // Stop
	//--------------------------------------------------------------------------
	return Index;
}

/*
********************************************************************************
*	ExecCmd
********************************************************************************
*/
int16_t ExecCmd(	uint8_t		Opcode,
                	uint8_t*	pData,
					uint8_t		Len ) {

 uint8_t	Index;
 uint8_t	Byte;

	//--------------------------------------------------------------------------
	write( fd, "\x55", 1 ); // Start
	//--------------------------------------------------------------------------
	write( fd, &Opcode, 1 ); read( fd, &Byte, 1 ); // Opcode
	//--------------------------------------------------------------------------
	Byte = Len;
	write( fd, &Byte, 1 ); // Len
	//--------------------------------------------------------------------------
	for( Index = 0; Index < Len; Index++ ) {
		//----------------------------------------------------------------------
		write( fd, &pData[Index], 1 ); read( fd, &Byte, 1 ); // Write Data
		//----------------------------------------------------------------------
	}
	//--------------------------------------------------------------------------
	write( fd, "\xAA", 1 ); // Stop
	//--------------------------------------------------------------------------
	return 0;
}

/*
********************************************************************************
*	ReadReg
********************************************************************************
*/
uint8_t ReadReg( uint16_t Reg ) {

 uint8_t	Byte;

	//--------------------------------------------------------------------------
	write( fd, "\x55", 1 ); // Start
	//--------------------------------------------------------------------------
	write( fd, "\x1D", 1 ); read( fd, &Byte, 1 ); // READ_REGISTER
	//--------------------------------------------------------------------------
	Byte = 4;
	write( fd, &Byte, 1 ); // Len
	//--------------------------------------------------------------------------
	write( fd, &((uint8_t*)&Reg)[1], 1 ); read( fd, &Byte, 1 );
	write( fd, &((uint8_t*)&Reg)[0], 1 ); read( fd, &Byte, 1 );
	//--------------------------------------------------------------------------
	write( fd, "\x00", 1 ); read( fd, &Byte, 1 ); // NOP
	//--------------------------------------------------------------------------
	write( fd, "\xFF", 1 ); read( fd, &Byte, 1 ); // Value
	//--------------------------------------------------------------------------
	write( fd, "\xAA", 1 ); // Stop
	//--------------------------------------------------------------------------
	return Byte;
}

/*
********************************************************************************
*	WriteReg
********************************************************************************
*/
void WriteReg(	uint16_t	Reg,
				uint8_t		Value ) {

 uint8_t	Byte;

	//--------------------------------------------------------------------------
	write( fd, "\x55", 1 ); // Start
	//--------------------------------------------------------------------------
	write( fd, "\x0D", 1 ); read( fd, &Byte, 1 ); // WRITE_REGISTER
	//--------------------------------------------------------------------------
	Byte = 3;
	write( fd, &Byte, 1 ); // Len
	//--------------------------------------------------------------------------
	write( fd, &((uint8_t*)&Reg)[1], 1 ); read( fd, &Byte, 1 );
	write( fd, &((uint8_t*)&Reg)[0], 1 ); read( fd, &Byte, 1 );
	//--------------------------------------------------------------------------
	write( fd, &Value, 1 ); read( fd, &Byte, 1 ); // Value
	//--------------------------------------------------------------------------
	write( fd, "\xAA", 1 ); // Stop
	//--------------------------------------------------------------------------
	return;
}

